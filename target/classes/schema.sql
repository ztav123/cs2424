-- Xóa bảng cũ để làm sạch (theo thứ tự để tránh lỗi khóa ngoại)
drop table CTHD cascade constraints;
drop table HOADON cascade constraints;
drop table CALAM cascade constraints;
drop table SANPHAM cascade constraints;
drop table KHACHHANG cascade constraints;
drop table NHANVIEN cascade constraints;

-- 1. BẢNG NHÂN VIÊN (Gộp cả Quản lý)
create table NHANVIEN (
    id number generated by default as identity primary key,
    hoten varchar2(100) not null,
    sdt varchar2(15),
    mkdangnhap varchar2(255) not null,
    vaitro varchar2(20) default 'NHANVIEN', -- 'ADMIN' hoặc 'NHANVIEN'
    trangthai number(1) default 1 -- 1: Đang làm, 0: Nghỉ việc
);

-- 2. BẢNG SẢN PHẨM (Gộp cả Kho hàng)
create table SANPHAM (
    id number generated by default as identity primary key,
    ten varchar2(100) not null,
    category varchar2(50),
    giaban number(15, 2) not null,
    tonkho number default 0, -- Gộp từ bảng KHO
    image_url varchar2(255)
);

-- 3. BẢNG KHÁCH HÀNG
create table KHACHHANG (
    sdt varchar2(15) primary key,
    hoten varchar2(100),
    diemtichluy number default 0,
    ngaytao date default sysdate
);

-- 4. BẢNG CA LÀM (Gộp báo cáo kết ca)
create table CALAM (
    id number generated by default as identity primary key,
    nhanvien_id number not null,
    batdau timestamp default systimestamp,
    ketthuc timestamp,
    tienmat_bandau number(15, 2) default 0,
    tienmat_ketca number(15, 2) default 0, -- Số tiền mặt nhân viên thực đếm
    tien_nganhang number(15, 2) default 0, -- Doanh thu từ CK/Momo (hệ thống tính)
    tong_doanhthu number(15, 2) default 0, -- Tổng tiền hệ thống tính (Cash + Bank)
    tongtien_thucte number(15, 2) default 0, -- Tổng thực tế có (Tiền mặt đếm + Bank)
    ghichu varchar2(255),
    constraint fk_calam_nv foreign key (nhanvien_id) references NHANVIEN(id)
);

-- 5. BẢNG HÓA ĐƠN (Gộp thông tin thanh toán)
create table HOADON (
    id varchar2(20) primary key,
    nhanvien_id number not null,
    khach_sdt varchar2(15),
    ngaylap timestamp default systimestamp,
    tongtien number(15, 2) not null,
    giamgia number(15, 2) default 0,
    -- Thông tin thanh toán gộp từ THANHTOAN
    phuongthuc_tt varchar2(20), -- 'TIEN_MAT', 'CHUYEN_KHOAN'
    trangthai varchar2(20) default 'HOAN_THANH',
    constraint fk_hd_nv foreign key (nhanvien_id) references NHANVIEN(id),
    constraint fk_hd_kh foreign key (khach_sdt) references KHACHHANG(sdt)
);

-- 6. CHI TIẾT HÓA ĐƠN
create table CTHD (
    hoadon_id varchar2(20) not null,
    sanpham_id number not null,
    soluong number not null,
    dongia number(15, 2) not null,
    primary key (hoadon_id, sanpham_id),
    constraint fk_cthd_hd foreign key (hoadon_id) references HOADON(id),
    constraint fk_cthd_sp foreign key (sanpham_id) references SANPHAM(id)
);

-- TRIGGER: Tự động gán tienmat_bandau khi tạo ca làm mới
CREATE OR REPLACE TRIGGER trg_calam_tienmat_bandau
FOR INSERT ON CALAM
COMPOUND TRIGGER

    -- Biến toàn cục trong trigger để lưu tiền kết ca của ca trước đó
    v_tien_ketca_truoc CALAM.tienmat_ketca%TYPE := 0;

    -- 1. BEFORE STATEMENT: Chạy duy nhất 1 lần trước khi câu lệnh INSERT bắt đầu
    BEFORE STATEMENT IS
    BEGIN
        BEGIN
            -- Tìm tienmat_ketca của ca làm việc gần nhất (ID lớn nhất)
            SELECT tienmat_ketca INTO v_tien_ketca_truoc
            FROM CALAM
            ORDER BY id DESC
            FETCH FIRST 1 ROWS ONLY;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                -- Xử lý trường hợp ID = 1 (bảng chưa có dòng nào)
                v_tien_ketca_truoc := 0;
        END;
    END BEFORE STATEMENT;

    -- 2. BEFORE EACH ROW: Chạy cho mỗi dòng chuẩn bị được INSERT vào
    BEFORE EACH ROW IS
    BEGIN
        -- Gán tiền mặt ban đầu bằng tiền kết ca của ca trước
        -- Chỉ tự động gán nếu người dùng để mặc định là 0 hoặc không truyền vào (NULL)
        IF :NEW.tienmat_bandau = 0 OR :NEW.tienmat_bandau IS NULL THEN
            :NEW.tienmat_bandau := NVL(v_tien_ketca_truoc, 0);
        END IF;

        -- Cập nhật lại biến để đề phòng trường hợp bạn INSERT nhiều dòng cùng lúc (INSERT ALL)
        -- Dòng thứ 2 sẽ lấy giá trị của dòng thứ 1 vừa tạo
        v_tien_ketca_truoc := NVL(:NEW.tienmat_ketca, 0);
    END BEFORE EACH ROW;

END trg_calam_tienmat_bandau;


